#!/usr/bin/env bash
# Regenerates src/Needle/EvexVnni.Code.cs from src/Needle/Asm/EvexVnni.s with GNU as.
# .NET 10 cannot emit EVEX VPDPBUSD (AVX512-VNNI) from managed code, so these few kernels
# ship as position-independent machine code that EvexVnni.cs maps executable at startup.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
as --64 "$root/src/Needle/Asm/EvexVnni.s" -o "$work/k.o"
objcopy -O binary -j .text "$work/k.o" "$work/k.bin"
python3 - "$work/k.o" "$work/k.bin" "$root/src/Needle/EvexVnni.Code.cs" <<'PY'
import subprocess, sys
obj, binary, out = sys.argv[1:]
code = open(binary, 'rb').read()
symbols = {}
for line in subprocess.check_output(['nm', obj], text=True).splitlines():
    address, kind, name = line.split()
    if kind == 'T': symbols[name] = int(address, 16)
rows = [', '.join('0x%02X' % b for b in code[i:i + 24]) for i in range(0, len(code), 24)]
body = '\n'.join('        ' + r + ',' for r in rows)
with open(out, 'w') as f:
    f.write('#if NEEDLE_SIMD\n// <auto-generated> by tools/asm-evex-vnni.sh from src/Needle/Asm/EvexVnni.s. Do not edit. </auto-generated>\n')
    f.write('namespace Needle;\n\ninternal static partial class EvexVnni\n{\n')
    for name in sorted(symbols, key=symbols.get):
        f.write('    const int %sOffset = %d;\n' % (name[0].upper() + name[1:], symbols[name]))
    f.write('\n    static System.ReadOnlySpan<byte> Code => new byte[]\n    {\n%s\n    };\n}\n#endif\n' % body)
PY
