using System.Collections.Generic;
using System.Text;

namespace Needle.Generators;

/// <summary>
/// Output for a <c>[Tools]</c> interface: the schema attribute, one arguments struct per tool, and
/// <c>Calls.Dispatch</c>. Written to compile as C# 9 so Unity projects can use it.
/// </summary>
internal static class ModernEmitter
{
    public static string Emit(ToolSetModel model)
    {
        var b = new StringBuilder(4096);
        b.Append("// <auto-generated by Needle.Generators; do not edit.>\n#nullable enable\n");
        var indent = "";
        if (!model.GlobalNamespace)
        {
            b.Append("namespace ").Append(model.Namespace).Append("\n{\n");
            indent = "    ";
        }
        var schema = Emitter.SchemaText(model);
        b.Append(indent).Append("[global::Needle.ToolSchema(\"").Append(Emitter.CSharpEscape(schema)).Append("\")]\n");
        b.Append(indent).Append("partial interface ").Append(model.InterfaceName).Append('\n').Append(indent).Append("{\n");
        var inner = indent + "    ";
        foreach (var tool in model.Tools) EmitArgs(b, tool, inner);
        EmitCalls(b, model, inner, schema);
        b.Append(indent).Append("}\n");
        if (!model.GlobalNamespace) b.Append("}\n");
        return b.ToString();
    }

    static string Field(ToolArg arg) => Emitter.Pascal(arg.Name);

    static void EmitArgs(StringBuilder b, ToolEntry tool, string indent)
    {
        var name = tool.Name + "Args";
        b.Append(indent).Append("/// <summary>The arguments of <c>").Append(tool.Name).Append("</c>.</summary>\n");
        b.Append(indent).Append("public struct ").Append(name).Append(" : global::Needle.IToolArgs<").Append(name).Append(">\n");
        b.Append(indent).Append("{\n");
        foreach (var arg in tool.Args)
            b.Append(indent).Append("    public ").Append(arg.SlotTypeName).Append(' ').Append(Field(arg)).Append(";\n");
        if (tool.Args.Length > 0) b.Append('\n');
        b.Append(indent).Append("    public string ToolName => \"").Append(Emitter.CSharpEscape(tool.Alias)).Append("\";\n\n");
        b.Append(indent).Append("    public bool TryRead(global::Needle.Call call, out ").Append(name).Append(" args)\n");
        b.Append(indent).Append("    {\n");
        b.Append(indent).Append("        args = default;\n");
        foreach (var arg in tool.Args) EmitRead(b, arg, indent + "        ");
        b.Append(indent).Append("        return true;\n");
        b.Append(indent).Append("    }\n");
        b.Append(indent).Append("}\n\n");
    }

    static void EmitRead(StringBuilder b, ToolArg arg, string indent)
    {
        var key = "\"" + Emitter.CSharpEscape(arg.Alias) + "\"";
        var target = "args." + Field(arg);
        var missing = arg.Optional ? "{ " + target + " = " + arg.DefaultLiteral + "; }" : "return false;";
        switch (arg.Type)
        {
            case ArgType.Int: Simple("TryGetInt32"); break;
            case ArgType.Long: Simple("TryGetInt64"); break;
            case ArgType.Float: Simple("TryGetSingle"); break;
            case ArgType.Double: Simple("TryGetDouble"); break;
            case ArgType.Bool: Simple("TryGetBoolean"); break;
            case ArgType.Text:
                b.Append(indent).Append("if (!call.TryGetText(").Append(key).Append(", ").Append(target).Append(".Buffer, out ").Append(target).Append(".Length)) return false;\n");
                break;
            case ArgType.Enum:
                b.Append(indent).Append("if (call.TryGet(").Append(key).Append(", out var ").Append(arg.Name).Append("Text))\n");
                b.Append(indent).Append("{\n");
                for (var i = 0; i < arg.EnumLiterals.Length; i++)
                {
                    b.Append(indent).Append(i == 0 ? "    if" : "    else if").Append(" (").Append(arg.Name).Append("Text.Equals(\"")
                        .Append(Emitter.CSharpEscape(arg.EnumLiterals[i])).Append("\")) ").Append(target).Append(" = ")
                        .Append(arg.EnumTypeName).Append('.').Append(arg.EnumMembers[i]).Append(";\n");
                }
                b.Append(indent).Append("    else return false;\n");
                b.Append(indent).Append("}\n");
                b.Append(indent).Append("else ").Append(missing).Append('\n');
                break;
        }

        void Simple(string reader) =>
            b.Append(indent).Append("if (!call.").Append(reader).Append('(').Append(key).Append(", out ").Append(target).Append(")) ").Append(missing).Append('\n');
    }

    static void EmitCalls(StringBuilder b, ToolSetModel model, string indent, string schema)
    {
        var iface = model.InterfaceName;
        b.Append(indent).Append("/// <summary>The schema and dispatch helpers for <c>").Append(iface).Append("</c>.</summary>\n");
        b.Append(indent).Append("public static class Calls\n").Append(indent).Append("{\n");
        b.Append(indent).Append("    /// <summary>The tools as the OpenAI-style JSON array the model sees.</summary>\n");
        b.Append(indent).Append("    public const string Schema = \"").Append(Emitter.CSharpEscape(schema)).Append("\";\n\n");
        b.Append(indent).Append("    /// <summary>Invokes the method of <paramref name=\"handler\"/> that <paramref name=\"call\"/> names. False when the call is not one of these tools or its arguments do not read.</summary>\n");
        b.Append(indent).Append("    public static bool Dispatch<THandler>(global::Needle.Call call, ref THandler handler) where THandler : ").Append(iface).Append('\n');
        b.Append(indent).Append("    {\n");
        foreach (var tool in model.Tools)
        {
            var local = "a" + tool.Name;
            b.Append(indent).Append("        if (call.Is(out ").Append(tool.Name).Append("Args ").Append(local).Append("))\n");
            b.Append(indent).Append("        {\n");
            var arguments = new List<string>();
            foreach (var arg in tool.Args)
            {
                var value = local + "." + Field(arg);
                arguments.Add(arg.Type == ArgType.Text && !arg.PassTextThrough ? value + ".ToString()" : value);
            }
            b.Append(indent).Append("            handler.").Append(tool.Name).Append('(').Append(string.Join(", ", arguments)).Append(");\n");
            b.Append(indent).Append("            return true;\n");
            b.Append(indent).Append("        }\n");
        }
        b.Append(indent).Append("        return false;\n");
        b.Append(indent).Append("    }\n\n");
        b.Append(indent).Append("    public static bool Dispatch<THandler>(global::Needle.Call call, THandler handler) where THandler : ").Append(iface).Append(" => Dispatch(call, ref handler);\n\n");
        b.Append(indent).Append("    /// <summary>Invokes every call of <paramref name=\"answer\"/> in order and returns how many ran.</summary>\n");
        b.Append(indent).Append("    public static int Dispatch<THandler>(global::Needle.Answer answer, ref THandler handler) where THandler : ").Append(iface).Append('\n');
        b.Append(indent).Append("    {\n");
        b.Append(indent).Append("        var count = 0;\n");
        b.Append(indent).Append("        foreach (var call in answer)\n");
        b.Append(indent).Append("            if (Dispatch(call, ref handler)) count++;\n");
        b.Append(indent).Append("        return count;\n");
        b.Append(indent).Append("    }\n\n");
        b.Append(indent).Append("    public static int Dispatch<THandler>(global::Needle.Answer answer, THandler handler) where THandler : ").Append(iface).Append(" => Dispatch(answer, ref handler);\n");
        b.Append(indent).Append("}\n");
    }
}
